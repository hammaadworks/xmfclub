-- 3. STORAGE BUCKET & STORAGE POLICIES
-- ==============================================================================
-- Create the public storage bucket for student & member photos
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
    'member-photos',
    'member-photos',
    true,
    10485760, -- 10MB limit per image
    ARRAY['image/png', 'image/jpeg', 'image/jpg', 'image/webp', 'image/gif']
)
ON CONFLICT (id) DO UPDATE SET
    public = true,
    file_size_limit = 10485760,
    allowed_mime_types = ARRAY['image/png', 'image/jpeg', 'image/jpg', 'image/webp', 'image/gif'];

-- Drop existing storage policies if re-running
DROP POLICY IF EXISTS "Public Access Member Photos" ON storage.objects;
DROP POLICY IF EXISTS "Allow Uploads Member Photos" ON storage.objects;
DROP POLICY IF EXISTS "Allow Updates Member Photos" ON storage.objects;
DROP POLICY IF EXISTS "Allow Deletes Member Photos" ON storage.objects;

-- 3.1. Public Read Policy on member-photos
CREATE POLICY "Public Access Member Photos"
ON storage.objects FOR SELECT
USING (bucket_id = 'member-photos');

-- 3.2. Public/Anon Insert Policy on member-photos
CREATE POLICY "Allow Uploads Member Photos"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'member-photos');

-- 3.3. Public/Anon Update Policy on member-photos
CREATE POLICY "Allow Updates Member Photos"
ON storage.objects FOR UPDATE
USING (bucket_id = 'member-photos');

-- 3.4. Public/Anon Delete Policy on member-photos
CREATE POLICY "Allow Deletes Member Photos"
ON storage.objects FOR DELETE
USING (bucket_id = 'member-photos');

