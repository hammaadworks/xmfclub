-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ==============================================================================
-- 1. TABLES (DDL)
-- ==============================================================================

-- 1.1. App Settings Table
CREATE TABLE IF NOT EXISTS public.app_settings (
    id TEXT PRIMARY KEY,
    branches JSONB DEFAULT '[]'::jsonb NOT NULL,
    belts JSONB DEFAULT '[]'::jsonb NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 1.2. Members Table
CREATE TABLE IF NOT EXISTS public.members (
    member_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    dob DATE,
    age INTEGER,
    phone TEXT,
    email TEXT,
    role TEXT DEFAULT 'student' NOT NULL, -- 'student', 'instructor', 'volunteer', 'admin'
    belt TEXT DEFAULT 'White' NOT NULL,
    member_status TEXT DEFAULT 'Active' NOT NULL, -- 'Active', 'Inactive', 'Discontinued'
    fee_status TEXT DEFAULT 'Paid' NOT NULL, -- 'Paid', 'Pending', 'Overdue'
    password TEXT NOT NULL DEFAULT '12345',
    address TEXT,
    pin_code TEXT, -- Residential address PIN / postal code
    branch TEXT DEFAULT 'XMF Main HQ',
    blood_group TEXT,
    date_of_joining DATE DEFAULT CURRENT_DATE,
    date_of_leaving DATE,
    achievements TEXT,
    instructor_remarks TEXT,
    instructor_remarks_color TEXT DEFAULT 'green',
    actual_fee NUMERIC(10, 2) DEFAULT 0,
    fee_detail TEXT,
    due_date DATE,
    pending_amount NUMERIC(10, 2) DEFAULT 0,
    photo_url TEXT,
    is_reviewed BOOLEAN DEFAULT false NOT NULL,
    is_deleted BOOLEAN DEFAULT false NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 1.3. Attendance Table
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id TEXT NOT NULL REFERENCES public.members(member_id) ON UPDATE CASCADE ON DELETE CASCADE,
    belt TEXT,
    timestamp TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 1.4. Events Table
CREATE TABLE IF NOT EXISTS public.events (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title TEXT NOT NULL,
    description TEXT,
    target_belt TEXT DEFAULT 'All',
    date TIMESTAMPTZ NOT NULL,
    time TEXT DEFAULT '10:00',
    fee NUMERIC(10, 2) DEFAULT 0,
    fee_breakup JSONB DEFAULT '{"total": 0}'::jsonb,
    venue_name TEXT DEFAULT 'XMF Main HQ',
    venue_map_url TEXT,
    banner_url TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 1.5. Event Registrations Table
CREATE TABLE IF NOT EXISTS public.event_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
    member_id TEXT NOT NULL REFERENCES public.members(member_id) ON UPDATE CASCADE ON DELETE CASCADE,
    status TEXT DEFAULT 'Registered' NOT NULL,
    registered_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_event_member UNIQUE (event_id, member_id)
);

-- 1.6. Sequences for Crockford Base32 Batch Indices (starts at 0)
CREATE SEQUENCE IF NOT EXISTS public.qrc_batch_seq START 0 MINVALUE 0;
CREATE SEQUENCE IF NOT EXISTS public.tag_batch_seq START 0 MINVALUE 0;

-- 1.7. Batches Table (Fixed 32 items per batch)
CREATE TABLE IF NOT EXISTS public.credential_batches (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    batch_number INTEGER NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('qrc', 'tag')),
    quantity INTEGER NOT NULL DEFAULT 32 CHECK (quantity = 32),
    start_token TEXT NOT NULL,
    end_token TEXT NOT NULL,
    configuration JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_by TEXT REFERENCES public.members(member_id),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_batch_per_type UNIQUE (type, batch_number)
);

-- 1.8. Reusable Physical Credentials Table
CREATE TABLE IF NOT EXISTS public.credentials (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    type TEXT NOT NULL CHECK (type IN ('qrc', 'tag')),
    token TEXT NOT NULL, -- 6-digit Crockford Base32 (e.g. 000000, 000010)
    status TEXT NOT NULL DEFAULT 'free' CHECK (status IN ('free', 'assigned', 'deleted')),
    batch_id UUID REFERENCES public.credential_batches(id),
    physical_uid TEXT, -- Manufacturer chip UID (e.g. 04:A3:91:72:8C:11)
    rejection_reason TEXT, -- 'printing_error', 'damaged', 'misaligned', 'chip_failure', 'other'
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_token_per_type UNIQUE (type, token)
);

-- 1.9. Credential Assignments Table (Audit & Active Linkage)
CREATE TABLE IF NOT EXISTS public.credential_assignments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    credential_id UUID NOT NULL REFERENCES public.credentials(id) ON DELETE CASCADE,
    member_id TEXT NOT NULL REFERENCES public.members(member_id) ON UPDATE CASCADE ON DELETE CASCADE,
    assigned_by TEXT REFERENCES public.members(member_id),
    assigned_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    unassigned_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- ==============================================================================
-- 2. INDEXES
-- ==============================================================================
CREATE UNIQUE INDEX IF NOT EXISTS one_active_assignment_per_credential ON public.credential_assignments(credential_id) WHERE unassigned_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_credential_assignments_member_id ON public.credential_assignments(member_id);
CREATE INDEX IF NOT EXISTS idx_credentials_status ON public.credentials(status);
CREATE INDEX IF NOT EXISTS idx_credentials_token ON public.credentials(token);

CREATE INDEX IF NOT EXISTS idx_members_member_id ON public.members(member_id);
CREATE INDEX IF NOT EXISTS idx_members_phone ON public.members(phone);
CREATE INDEX IF NOT EXISTS idx_members_is_deleted ON public.members(is_deleted);
CREATE INDEX IF NOT EXISTS idx_members_is_reviewed ON public.members(is_reviewed);
CREATE INDEX IF NOT EXISTS idx_members_belt ON public.members(belt);
CREATE INDEX IF NOT EXISTS idx_members_branch ON public.members(branch);
CREATE INDEX IF NOT EXISTS idx_members_pin_code ON public.members(pin_code);
CREATE INDEX IF NOT EXISTS idx_members_created_at ON public.members(created_at DESC);

CREATE INDEX IF NOT EXISTS idx_attendance_member_id ON public.attendance(member_id);
CREATE INDEX IF NOT EXISTS idx_attendance_timestamp ON public.attendance(timestamp DESC);

CREATE INDEX IF NOT EXISTS idx_events_date ON public.events(date ASC);
CREATE INDEX IF NOT EXISTS idx_event_registrations_event_id ON public.event_registrations(event_id);
CREATE INDEX IF NOT EXISTS idx_event_registrations_member_id ON public.event_registrations(member_id);

